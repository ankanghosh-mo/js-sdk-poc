// Builds the downloadable SDK files in the browser: what the kit's ddm-compile.mjs does on the command line.
//   source (mapping-source.json) -> compile -> configHash -> contract check -> ddm-map.js + ddm-sdk.js
import { ddmCompile, ddmCheckV12, ddmCanonicalJson, engineJs, ENGINE_VERSION } from './ddmKit.js';
import { sha256Hex, sriSha384 } from './sha.js';

const inlineSafe = (s) => s.replace(/</g, '\\u003c');   // no closing script tag can appear inside the files

/** Compile only (no hashing, no files): errors and warnings for the Submit checks. */
export function previewCompile(source) {
  const { errors, warnings } = ddmCompile(JSON.parse(JSON.stringify(source)));
  return { errors, warnings };
}

export async function buildSdk(source) {
  const { compiled, errors, warnings } = ddmCompile(JSON.parse(JSON.stringify(source)));
  if (errors.length) return { ok: false, errors, warnings };

  // configHash: SHA-256 of the canonical JSON of the payload without meta.configHash (spec section 6)
  const forHash = JSON.parse(JSON.stringify(compiled));
  delete forHash.meta.configHash;
  compiled.meta.configHash = 'sha256:' + sha256Hex(ddmCanonicalJson(forHash));

  const check = ddmCheckV12(JSON.parse(JSON.stringify(compiled)), undefined, { sha256Hex });
  if (check.errors.length) return { ok: false, errors: check.errors, warnings };

  const mapJs =
    `/*! DAM Capital DDM map ${compiled.configVersion} (V12) - generated by the DDM console. Do not edit; change the rules and build again. */\n` +
    `(function(){var c=${inlineSafe(JSON.stringify(compiled))};if(!window.DAM_DDM_CONFIG){Object.defineProperty(window,'DAM_DDM_CONFIG',{value:c,writable:false,configurable:false});}})();\n`;
  const sdkJs = mapJs + '\n' + engineJs;
  const sourceJson = JSON.stringify(source, null, 2) + '\n';

  return {
    ok: true,
    warnings: [...warnings, ...check.warnings.filter((w) => !warnings.includes(w))],
    compiled,
    configHash: compiled.meta.configHash,
    engineVersion: ENGINE_VERSION,
    files: { 'ddm-sdk.js': sdkJs, 'ddm-map.js': mapJs, 'ddm-engine.js': engineJs, 'mapping-source.json': sourceJson },
    integrity: { 'ddm-sdk.js': await sriSha384(sdkJs), 'ddm-map.js': await sriSha384(mapJs), 'ddm-engine.js': await sriSha384(engineJs) },
    builtAt: new Date(),
  };
}

export function readmeFor(build, mode) {
  const f = build.files, i = build.integrity;
  const one = `<script src="/vendor/ddm-sdk.js"\n        integrity="${i['ddm-sdk.js']}" crossorigin="anonymous"></script>`;
  const two = `<script src="/vendor/ddm-map.js"\n        integrity="${i['ddm-map.js']}" crossorigin="anonymous"></script>\n` +
              `<script src="/vendor/ddm-engine.js"\n        integrity="${i['ddm-engine.js']}" crossorigin="anonymous"></script>`;
  return (mode === 'two' ? two : one);
}

export function readmeMarkdown(build, mode, name) {
  const code = readmeFor(build, mode);
  return `# ${name}: developer README

Map ${build.compiled.configVersion} (V12), engine v${build.engineVersion}.
configHash ${build.configHash}

## Add it to your pages

Copy ${mode === 'two' ? '`ddm-map.js` and `ddm-engine.js`' : '`ddm-sdk.js`'} to \`/vendor/\` on your web server, then make this the **first script in \`<head>\`**,
without \`async\` or \`defer\`:

\`\`\`html
${code}
\`\`\`
${mode === 'two' ? '\nThe map must load before the engine.\n' : ''}
The approved rules are already inside; there is nothing to configure and no start-up call.

## Check it works

- Open a page that shows a masked field: the value is hidden.
- In the browser console: \`DamDDM.stats()\` and \`DamDDM.meta\`.
- Debug messages: set \`window.DAM_DDM_DEBUG = true\` before the script.

## Limits

This is browser-side UI masking. The original values still exist in network responses, page source and application state.
See DDM-V12-SPEC.md section 5 and 9 for what the SDK cannot hide.
`;
}

export function download(name, text, type) {
  const url = URL.createObjectURL(new Blob([text], { type: type || 'text/javascript' }));
  const a = document.createElement('a');
  a.href = url; a.download = name;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
